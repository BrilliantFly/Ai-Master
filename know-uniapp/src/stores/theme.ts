interface ThemeStore {
    primaryColor: string
    minorColor: string
    btnColor: string
    navColor: string
    navBgColor: string
    vars: string
    currentVisualTheme: string
}
export const useThemeStore = defineStore({
    id: 'themeStore',
    state: (): ThemeStore => ({
        primaryColor: '',
        minorColor: '',
        btnColor: 'white',
        navColor: '#000000',
        navBgColor: '#ffffff',
        vars: '',
        currentVisualTheme: 'white'
    }),
    getters: {
        /** 当前视觉主题对象 */
        currentThemeConfig: (state) => {
            return VISUAL_THEMES.find((t) => t.key === state.currentVisualTheme) || VISUAL_THEMES[0]
        },
        /** 当前主题的 CSS 变量对象（全端适用）
         *  1. 取视觉主题的完整色值表（THEME_COLORS）
         *  2. 若有服务端配色（getDecorate），覆盖 primary / minor / btn-text
         */
        themeInlineVars: (state): Record<string, string> => {
            const base = THEME_COLORS[state.currentVisualTheme] || THEME_COLORS.white
            const server = {
                primaryColor: state.primaryColor,
                minorColor: state.minorColor,
                btnColor: state.btnColor
            }
            // 有服务端配色时才合并覆盖
            return server.primaryColor ? mergeServerColors(base, server) : base
        }
    },
    actions: {
        async getTheme() {
            // 1. 先同步恢复保存的视觉主题（渲染前立即生效，配合 App.vue setup 中的 data-theme 设置）
            const saved = uni.getStorageSync(THEME_STORAGE_KEY)
            if (saved) {
                this.currentVisualTheme = saved
                this.applyVisualTheme(saved)
            }

            // 2. 再异步拉取服务端配色（覆盖主色/辅色/按钮文字色）
            const data = await getDecorate({
                id: 5
            })
            const { themeColor1, themeColor2, buttonColor, navigationBarColor, topTextColor } = data
            this.primaryColor = themeColor1
            this.minorColor = themeColor2
            this.btnColor = buttonColor
            this.navColor = topTextColor === 'white' ? '#ffffff' : '#000000'
            this.navBgColor = navigationBarColor || themeColor1
            this.vars = generateVars(
                {
                    primary: themeColor1
                },
                {
                    '--color-minor': themeColor2,
                    '--color-btn-text': buttonColor
                }
            )
        },
        /** 切换视觉主题 */
        setVisualTheme(key: string) {
            this.currentVisualTheme = key
            uni.setStorageSync(THEME_STORAGE_KEY, key)
            this.applyVisualTheme(key)
        },
        /** 将主题应用到当前页面（全端） */
        applyVisualTheme(key: string) {
            // H5：通过 data-theme 属性 + themes.scss
            // #ifdef H5
            document.documentElement.setAttribute('data-theme', key)
            // #endif
            // 小程序/App：通过 themeInlineVars getter 自动绑定内联样式
        },
        setTheme(color: string) {
            this.primaryColor = color
        }
    }
})
